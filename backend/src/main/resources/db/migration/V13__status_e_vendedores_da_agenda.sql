-- Status e vendedores da agenda passam a ser editados na propria agenda (Diretoria e
-- Administrador), como os adesivadores.

-- Os status. Os seis do sistema (chave preenchida) tem regra por tras - executando,
-- concluido... - e so mudam de nome e cor. Os criados na agenda (chave nula) sao
-- etiquetas de um servico que ainda nao comecou, e podem ser removidos.
CREATE TABLE status_agenda (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave  VARCHAR(20),
    nome   VARCHAR(40) NOT NULL,
    cor    VARCHAR(7)  NOT NULL,
    ordem  INTEGER     NOT NULL,
    CONSTRAINT uk_status_agenda_chave UNIQUE (chave)
);

