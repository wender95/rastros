ALTER TABLE agendamentos ADD COLUMN etiqueta_id BIGINT REFERENCES status_agenda (id);

-- Os vendedores da agenda: o codigo (a letra do cronograma) e o que fica gravado no card.
-- A lista inicial vem dos usuarios do comercial (V14).
CREATE TABLE vendedores_agenda (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(5)  NOT NULL,
    nome   VARCHAR(60) NOT NULL,
    ativo  BOOLEAN     NOT NULL,
    CONSTRAINT uk_vendedores_agenda_codigo UNIQUE (codigo)
);
